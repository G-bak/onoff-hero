import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import sharp from 'sharp';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const sourceDir = path.join(root, 'design/why-universe');
const assetDir = path.join(root, 'app/assets/why-universe');
const gifDir = path.join(root, 'design/archive/public/images/why-universe');
const sequence = [0, 1, 2, 3, 4, 5, 6, 7, 6, 5, 4, 3, 2, 1];
const delays = sequence.map((_, i) => (i === 0 ? 800 : i === 7 ? 500 : 110));
const duration = delays.reduce((sum, value) => sum + value, 0);
const width = 240,
  height = 320;
const source = await sharp(path.join(sourceDir, 'pose-sheet.png'))
  .ensureAlpha()
  .raw()
  .toBuffer({ resolveWithObject: true });
assert.equal(source.info.width % 4, 0);
assert.equal(source.info.height % 2, 0);
const cellWidth = source.info.width / 4,
  cellHeight = source.info.height / 2;
assert.ok(
  source.data.some((value, index) => index % 4 === 3 && value === 0),
  'The source must contain real transparency.',
);
await Promise.all(
  [assetDir, gifDir, path.join(sourceDir, 'frames')].map((dir) =>
    fs.mkdir(dir, { recursive: true }),
  ),
);
const frames = [],
  alignments = [];
for (let index = 0; index < 8; index++) {
  const rgba = await sharp(source.data, { raw: source.info })
    .extract({
      left: (index % 4) * cellWidth,
      top: Math.floor(index / 4) * cellHeight,
      width: cellWidth,
      height: cellHeight,
    })
    .raw()
    .toBuffer();
  let bottom = 0,
    left = cellWidth,
    right = 0;
  for (let y = Math.floor(cellHeight * 0.85); y < cellHeight; y++)
    for (let x = 0; x < cellWidth; x++)
      if (rgba[(y * cellWidth + x) * 4 + 3] > 127) {
        bottom = Math.max(bottom, y);
        left = Math.min(left, x);
        right = Math.max(right, x);
      }
  assert.ok(
    bottom > cellHeight * 0.88 && right > left,
    `Frame ${index}: incomplete feet.`,
  );
  const dx = Math.round(cellWidth / 2 - (left + right) / 2),
    dy = cellHeight - 12 - bottom;
  const aligned = Buffer.alloc(cellWidth * cellHeight * 4);
  for (let y = 0; y < cellHeight; y++)
    for (let x = 0; x < cellWidth; x++) {
      const targetX = x + dx,
        targetY = y + dy,
        offset = (y * cellWidth + x) * 4;
      if (
        targetX < 0 ||
        targetX >= cellWidth ||
        targetY < 0 ||
        targetY >= cellHeight
      ) {
        assert.ok(
          rgba[offset + 3] < 128,
          `Frame ${index}: alignment clips the person.`,
        );
        continue;
      }
      rgba.copy(
        aligned,
        (targetY * cellWidth + targetX) * 4,
        offset,
        offset + 4,
      );
    }
  const frame = await sharp(aligned, {
    raw: { width: cellWidth, height: cellHeight, channels: 4 },
  })
    .resize(width, height)
    .png()
    .toBuffer();
  frames.push(frame);
  alignments.push({ index, dx, dy });
  await fs.writeFile(
    path.join(sourceDir, `frames/pose-${index + 1}.png`),
    frame,
  );
}
const sprite = await sharp({
  create: { width: width * 8, height, channels: 4, background: '#00000000' },
})
  .composite(
    frames.map((input, index) => ({ input, left: index * width, top: 0 })),
  )
  .webp({ quality: 90, alphaQuality: 100, effort: 6 })
  .toBuffer();
await fs.writeFile(path.join(assetDir, 'conductor-sprite.webp'), sprite);
const rawFrames = await Promise.all(
  frames.map((frame) => sharp(frame).ensureAlpha().raw().toBuffer()),
);
const gif = await sharp(
  Buffer.concat(sequence.map((index) => rawFrames[index])),
  {
    raw: {
      width,
      height: height * sequence.length,
      channels: 4,
      pageHeight: height,
    },
  },
)
  .gif({ loop: 0, delay: delays, effort: 7, colours: 256, dither: 0.3 })
  .toBuffer();
await fs.writeFile(path.join(gifDir, 'conductor.gif'), gif);
const meta = await sharp(gif, { animated: true }).metadata();
assert.equal(meta.pages, sequence.length);
assert.deepEqual(meta.delay, delays);
assert.ok(meta.hasAlpha);
let elapsed = 0;
const stops = sequence.map((frame, index) => {
  const percent = (elapsed / duration) * 100;
  elapsed += delays[index];
  return `  ${percent.toFixed(6)}% { background-position: ${((frame / 7) * 100).toFixed(6)}% 0; }`;
});
await fs.writeFile(
  path.join(assetDir, 'person.css'),
  `/* Generated by npm run prepare:why-person. Same timeline as conductor.gif. */\n.why-person { aspect-ratio: ${width} / ${height}; background-size: 800% 100%; animation: why-conductor ${duration}ms steps(1, end) infinite; animation-play-state: paused; }\n.site-pages:not([inert]) .why-section[data-visible='true'] .why-person.is-in-viewport:not(.is-document-hidden) { animation-play-state: running; }\n@keyframes why-conductor {\n${stops.join('\n')}\n  100% { background-position: 0 0; }\n}\n`,
);
await fs.writeFile(
  path.join(sourceDir, 'animation.json'),
  JSON.stringify(
    {
      width,
      height,
      frames: 8,
      sequence,
      delays,
      duration,
      alignments,
      spriteBytes: sprite.length,
      gifBytes: gif.length,
    },
    null,
    2,
  ) + '\n',
);
console.log(
  `WHY conductor: ${width}x${height}, 8 poses, ${duration}ms, sprite ${sprite.length} bytes / GIF ${gif.length} bytes.`,
);
