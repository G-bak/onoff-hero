import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import sharp from 'sharp';

// One timeline produces both the downloadable GIF and the pausable web sprite.
const sequence = [0, 1, 2, 3, 4, 5, 6, 7, 6, 5, 4, 3, 2, 1];
const delays = sequence.map((_, i) => i === 0 ? 1500 : i === 7 ? 820 : 130);
const duration = delays.reduce((total, delay) => total + delay, 0);
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const assetDir = path.join(root, 'app/assets/why-person');
const designDir = path.join(root, 'design/why-person');
const gifDir = path.join(root, 'design/archive/public/images/why-person');
const width = 256, height = 337, cellWidth = 384, cellHeight = 512;
const source = await sharp(path.join(designDir, 'pose-sheet-green.png')).ensureAlpha().raw().toBuffer({resolveWithObject:true});
assert.equal(source.info.width, cellWidth * 4);
assert.equal(source.info.height, cellHeight * 2);
await Promise.all([assetDir, gifDir, path.join(designDir, 'frames')].map(dir => fs.mkdir(dir, {recursive:true})));

const frames = [];
const alignments = [];
for (let index = 0; index < 8; index++) {
  const rgba = Buffer.alloc(cellWidth * cellHeight * 4);
  const col = index % 4, row = Math.floor(index / 4);
  for (let y = 0; y < cellHeight; y++) for (let x = 0; x < cellWidth; x++) {
    const input = ((row * cellHeight + y) * source.info.width + col * cellWidth + x) * 4;
    const output = (y * cellWidth + x) * 4;
    const [r, g, b] = source.data.subarray(input, input + 3);
    const spill = Math.max(0, g - Math.max(r, b) - 6);
    const alpha = Math.max(0, 1 - spill / 190);
    if (alpha < .04) continue;
    rgba[output] = Math.min(255, Math.round(r / alpha));
    rgba[output + 1] = spill > 0 ? Math.min(rgba[output], Math.round(b / alpha)) : g;
    rgba[output + 2] = Math.min(255, Math.round(b / alpha));
    rgba[output + 3] = Math.round(alpha * 255);
  }
  // Align the feet, not the changing raised-hand bounds. This prevents a jump
  // when the next pose is narrower or has a higher pointing hand.
  let bottom = 0, left = cellWidth, right = 0;
  for (let y = 450; y < cellHeight; y++) for (let x = 0; x < cellWidth; x++) {
    if (rgba[(y * cellWidth + x) * 4 + 3] > 127) { bottom = Math.max(bottom, y); left = Math.min(left, x); right = Math.max(right, x); }
  }
  assert.ok(bottom > 480 && right > left, `Pose ${index} has no complete feet.`);
  const dx = 210 - Math.round((left + right) / 2), dy = 504 - bottom;
  const aligned = Buffer.alloc(cellWidth * 505 * 4);
  for (let y = 0; y < cellHeight; y++) for (let x = 0; x < cellWidth; x++) {
    const targetX = x + dx, targetY = y + dy;
    if (targetX < 0 || targetX >= cellWidth || targetY < 0 || targetY >= 505) {
      assert.ok(rgba[(y * cellWidth + x) * 4 + 3] < 128, `Pose ${index} would crop the figure.`);
      continue;
    }
    rgba.copy(aligned, (targetY * cellWidth + targetX) * 4, (y * cellWidth + x) * 4, (y * cellWidth + x) * 4 + 4);
  }
  const frame = await sharp(aligned, {raw:{width:cellWidth,height:505,channels:4}}).resize(width,height).png().toBuffer();
  await fs.writeFile(path.join(designDir, `frames/pose-${String(index + 1).padStart(2, '0')}.png`),frame);
  frames.push(frame);
  alignments.push({index,dx,dy});
}

const sprite = await sharp({create:{width:width * 8,height,channels:4,background:'#00000000'}})
  .composite(frames.map((input,index) => ({input,left:index * width,top:0}))).webp({quality:90,alphaQuality:100,effort:6}).toBuffer();
await fs.writeFile(path.join(assetDir, 'gesture-sprite.webp'), sprite);
const rgbaFrames = await Promise.all(frames.map(frame => sharp(frame).ensureAlpha().raw().toBuffer()));
const gif = await sharp(Buffer.concat(sequence.map(frame => rgbaFrames[frame])), {raw:{width,height:height * sequence.length,channels:4,pageHeight:height}})
  .gif({loop:0,delay:delays,effort:7,colours:256,dither:.3}).toBuffer();
await fs.writeFile(path.join(gifDir, 'gesture.gif'), gif);
const metadata = await sharp(gif,{animated:true}).metadata();
assert.equal(metadata.pages, sequence.length);
assert.deepEqual(metadata.delay, delays);
assert.ok(metadata.hasAlpha, 'The exported GIF must have a transparent background.');

let elapsed = 0;
const stops = sequence.map((frame,index) => {
  const percent = (elapsed / duration * 100).toFixed(6);
  elapsed += delays[index];
  return `  ${percent}% { background-position: ${(frame / 7 * 100).toFixed(6)}% 0; }`;
});
// The back page is already visible while the front is leaving. Waiting for
// is-turned freezes a visible person if scrolling stops just before the end.
// Scope the entry to its own back surface so nested page turns stay separate.
const css = `/* Generated by npm run prepare:why-person. Timing matches gesture.gif. */\n.why-person { aspect-ratio: ${width} / ${height}; background-size: 800% 100%; animation: why-person-gesture ${duration}ms steps(1, end) infinite; animation-play-state: paused; }\n.site-pages:not([inert]) .is-enhanced:is(.is-turning, .is-turned) > .page-turn-back-track > .section-surface .why-person.is-in-viewport:not(.is-document-hidden) { animation-play-state: running; }\n@keyframes why-person-gesture {\n${stops.join('\n')}\n  100% { background-position: 0 0; }\n}\n`;
await fs.writeFile(path.join(assetDir, 'gesture.css'),css);
await fs.writeFile(path.join(designDir, 'animation.json'),JSON.stringify({width,height,frames:8,sequence,delays,duration,alignments,spriteBytes:sprite.length,gifBytes:gif.length},null,2)+'\n');
console.log(`WHY person: 8 transparent poses, ${sequence.length}-frame / ${duration}ms loop; sprite ${sprite.length} bytes, GIF ${gif.length} bytes.`);
